-- The collections case queue: the operational record the collections team works, one row per
-- delinquent account.
--
-- Two kinds of column, and the split is the whole design:
--   MACHINE-OWNED  refreshed from the governed gold tables on every pipeline cycle (serve/sync_cases.py):
--                  the facts, the score and its drivers, the conduct flags, the AI brief.
--   HUMAN-OWNED    status, owner, notes, next action date. Written only by people through the app.
--                  The sync's upsert never names these columns, so a refresh can never overwrite a
--                  decision somebody made.
--
-- Every change to either kind is written to case_history by a trigger, not by application code, so
-- there is no code path that changes a case without leaving a record.

SET search_path TO ${LAKEBASE_SCHEMA};

CREATE TABLE IF NOT EXISTS collections_cases (
    case_id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    loan_account_id       TEXT NOT NULL UNIQUE,

    -- machine-owned -------------------------------------------------------------------------------
    region                TEXT NOT NULL,
    branch_id             TEXT NOT NULL,
    product_code          TEXT NOT NULL,
    snapshot_month        DATE NOT NULL,
    dpd_days              INTEGER NOT NULL,
    dpd_bucket            TEXT NOT NULL,
    outstanding_principal NUMERIC(16, 2) NOT NULL,
    priority_score        INTEGER NOT NULL,
    priority_rank         INTEGER NOT NULL,
    drivers               JSONB NOT NULL DEFAULT '[]'::jsonb,
    conduct_flags         JSONB NOT NULL DEFAULT '[]'::jsonb,
    recommended_treatment TEXT NOT NULL,
    ai_explanation        TEXT,
    ai_recommended_action TEXT,
    ai_prompt_version     TEXT,
    on_worklist           BOOLEAN NOT NULL DEFAULT TRUE,   -- false once the account is no longer delinquent
    refreshed_at          TIMESTAMPTZ NOT NULL,

    -- human-owned ---------------------------------------------------------------------------------
    status                TEXT NOT NULL DEFAULT 'new'
                          CHECK (status IN ('new', 'in_progress', 'promise_to_pay', 'on_hold', 'resolved', 'closed')),
    owner                 TEXT,
    notes                 TEXT,
    next_action_date      DATE,
    updated_by            TEXT,
    updated_at            TIMESTAMPTZ
);
CREATE INDEX IF NOT EXISTS collections_cases_region_rank ON collections_cases (region, priority_rank);

CREATE TABLE IF NOT EXISTS case_history (
    history_id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    case_id         BIGINT NOT NULL REFERENCES collections_cases(case_id),
    loan_account_id TEXT NOT NULL,
    changed_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
    changed_by      TEXT NOT NULL,
    change_source   TEXT NOT NULL,                  -- pipeline_sync | app
    field           TEXT NOT NULL,
    old_value       TEXT,
    new_value       TEXT
);
CREATE INDEX IF NOT EXISTS case_history_case ON case_history (case_id, changed_at);

-- The writer says who it is with SET LOCAL ct.change_source / ct.changed_by inside its transaction;
-- the sync sets pipeline_sync, the app sets app and the signed-in user.
CREATE OR REPLACE FUNCTION record_case_history() RETURNS trigger AS $$
DECLARE
    src TEXT := coalesce(nullif(current_setting('ct.change_source', true), ''), 'unknown');
    who TEXT := coalesce(nullif(current_setting('ct.changed_by', true), ''), current_user);
    f   TEXT;
    o   TEXT;
    n   TEXT;
BEGIN
    IF TG_OP = 'INSERT' THEN
        INSERT INTO case_history (case_id, loan_account_id, changed_by, change_source, field, new_value)
        VALUES (NEW.case_id, NEW.loan_account_id, who, src, 'case_opened',
                concat('rank ', NEW.priority_rank, ', ', NEW.recommended_treatment));
        RETURN NEW;
    END IF;
    -- Every business column, machine-owned and human-owned. Only refreshed_at and the updated_* stamps are
    -- left out: they change on every write and say nothing the changed_at and changed_by columns do not.
    FOREACH f IN ARRAY ARRAY['status', 'owner', 'notes', 'next_action_date',
                             'region', 'branch_id', 'product_code', 'snapshot_month', 'dpd_days', 'dpd_bucket',
                             'outstanding_principal', 'priority_score', 'priority_rank', 'drivers', 'conduct_flags',
                             'recommended_treatment', 'ai_explanation', 'ai_recommended_action', 'ai_prompt_version',
                             'on_worklist']
    LOOP
        EXECUTE format('SELECT ($1).%I::text, ($2).%I::text', f, f) INTO o, n USING OLD, NEW;
        IF o IS DISTINCT FROM n THEN
            INSERT INTO case_history (case_id, loan_account_id, changed_by, change_source, field, old_value, new_value)
            VALUES (NEW.case_id, NEW.loan_account_id, who, src, f, o, n);
        END IF;
    END LOOP;
    RETURN NEW;
END $$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS collections_cases_history ON collections_cases;
CREATE TRIGGER collections_cases_history AFTER INSERT OR UPDATE ON collections_cases
    FOR EACH ROW EXECUTE FUNCTION record_case_history();

-- Actions raised from a case point back at it, so the case shows what was proposed and decided.
ALTER TABLE actions ADD COLUMN IF NOT EXISTS case_id BIGINT REFERENCES collections_cases(case_id);
ALTER TABLE actions ADD COLUMN IF NOT EXISTS rejected_by TEXT;
