"""Render the three Genie agent specifications as GENIE_SPACES.md and their benchmarks as GENIE_BENCHMARKS.md.

    python3 tools/render_genie_spec.py

The specifications are generated by `genie/create_genie_agents.py --write` into `genie/spaces/*.geniespace.json`
(what is deployed) and `app/backend/*_space.md` (the same content as markdown, read by the app's fallback).
This script concatenates the markdown copies and appends every benchmark question with its ground-truth SQL,
so the full specification can be read at the repository root. Two files, so each stays small enough to read whole.
"""
from __future__ import annotations

import json
import os
from pathlib import Path

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SPACES = [("collections", "Collections & Recovery"), ("grievance", "Service & Grievance"), ("rm", "RM Performance")]
BENCH = {"collections": "collections.jsonl", "grievance": "grievance.jsonl", "rm": "rm.jsonl"}


def main() -> None:
    spec = ["# Genie agent specifications", "",
            "<!-- GENERATED by tools/render_genie_spec.py from app/backend/*_space.md. Do not edit. -->", "",
            ("Three governed Genie agents are deployed by the bundle (`resources/genie.yml`) from one specification, "
             "`genie/create_genie_agents.py`. Each agent has the tables it may use with a description of each, the joins, "
             "the instructions, and worked example questions with SQL. `${FQ}` is the catalog and schema the bundle "
             "deploys to. The benchmark questions and their ground-truth SQL are in `GENIE_BENCHMARKS.md`; the graded "
             "results are in `evidence/08_genie.md` and `run_output/verify_run.ipynb`."), ""]
    bench = ["# Genie benchmark questions and ground-truth SQL", "",
             "<!-- GENERATED by tools/render_genie_spec.py from eval/benchmarks/*.jsonl. Do not edit. -->", "",
             ("Every question below was asked through the Genie Conversation API by `eval/run_eval.py genie` and graded "
              "against the SQL shown, run in the same minute. A second, held-out set is kept outside the repository so the agents "
              "cannot be tuned against it; its score is in `evidence/08_genie.md` with these results."), ""]
    for key, title in SPACES:
        md = Path(ROOT, "app", "backend", f"{key}_space.md").read_text()
        body = md.split("\n", 1)[1].replace("<!-- GENERATED by genie/create_genie_agents.py --write. Do not edit. -->", "").strip()
        body = "\n".join(("#" + line) if line.startswith("#") else line for line in body.splitlines())
        spec += [f"## Agent: {title}", "", body, ""]
        bench += [f"## {title}", ""]
        for line in Path(ROOT, "eval", "benchmarks", BENCH[key]).read_text().splitlines():
            c = json.loads(line)
            sql = c["golden_sql"] if isinstance(c["golden_sql"], str) else "\n".join(c["golden_sql"])
            bench += [f"**{c['id']}.** {c['question']}", "", "```sql", sql.strip(), "```", ""]
    bench += ["## Routing questions", "", "Questions the app's supervisor must send to the right agents. Graded on the agents chosen.", ""]
    for line in Path(ROOT, "eval", "benchmarks", "routing.jsonl").read_text().splitlines():
        c = json.loads(line)
        bench.append(f"- **{c['id']}** ({', '.join(c.get('expected_domains', []))}): {c['question']}")
    for name, lines in (("GENIE_SPACES.md", spec), ("GENIE_BENCHMARKS.md", bench)):
        path = os.path.join(ROOT, name)
        Path(path).write_text("\n".join(lines) + "\n")
        print("wrote", path, len("\n".join(lines)), "chars")


if __name__ == "__main__":
    main()
